"""Все настройки приложения в одном месте."""
import os

BASE = os.path.dirname(os.path.abspath(__file__))
ASSETS = os.path.join(BASE, "assets")
SOUNDS = os.path.join(BASE, "sounds")
CONFIG_PATH = os.path.join(BASE, "config.json")        # выбранная камера
CALIB_PATH = os.path.join(BASE, "calibration.json")    # калибровка взгляда
ACCURACY_LOG = os.path.join(BASE, "accuracy_log.csv")  # результаты теста точности
EVENTS_LOG = os.path.join(BASE, "events.csv")          # журнал тревог с причиной

# ---------------- камера ----------------
CAMERA_WIDTH = 640    # 0 = не менять разрешение. Для взгляда хватает 640x480: меньше нагрузка на USB и декодер
CAMERA_HEIGHT = 480
MAX_CAMERA_PROBE = 8  # сколько индексов проверять при поиске камер

# ---------------- тревоги ----------------
# Сколько секунд взгляд должен быть "не там", чтобы сработала тревога. Зависит от того, куда ушёл взгляд:
# вниз (телефон) - быстро, вбок и вверх (бумаги, второй монитор, задумался) - терпимее.
AWAY_SECONDS = {"down": 1.5, "up": 5.0, "side": 5.0, "head": 3.0, "noface": 2.5}
NO_FACE_AS_AWAY = True    # нет лица в кадре = тоже "отвёл взгляд"
ALERT_SHOW_SECONDS = 2.5  # максимум: тревога гаснет раньше, как только взгляд вернулся или телефон ушёл из кадра
ALERT_FADE_MS = 40        # звук при отмене затухает за столько мс (мгновенно для уха, но без щелчка)
COOLDOWN_SECONDS = 4.0    # пауза между срабатываниями одного типа
FULLSCREEN_ALERT = True   # картинка на весь экран (Windows)

# ---------------- телефон ----------------
PHONE_CONF = 0.35     # порог уверенности YOLO
PHONE_HITS = 3        # из последних PHONE_WINDOW детекций нужно столько попаданий
PHONE_WINDOW = 5
PHONE_IMGSZ = 416     # размер входа YOLO: меньше = быстрее, но хуже видит мелкие предметы
PHONE_MAX_FPS = 10    # потолок частоты детекций (YOLO работает в фоновом потоке)
PHONE_FAST_FPS = 25   # частота детекций, пока показывается тревога про телефон: быстрее заметим, что телефон убрали
PHONE_CLEAR_MISSES = 2  # телефон "ушёл", когда его нет в стольких последних детекциях подряд (1 = мгновенно, но мигает)

# ---------------- взгляд: признаки ----------------
# yaw/pitch - поворот и наклон головы; iris_h/iris_v - зрачок относительно уголков глаз
# (в долях ширины глаза); eye_open - раскрытие глаз (при взгляде вниз веки опускаются)
FEATURE_NAMES = ("yaw", "pitch", "iris_h", "iris_v", "eye_open")
SMOOTH_ALPHA = 0.5        # лёгкое сглаживание признаков (0..1, меньше = плавнее)
BLINK_REL = 0.55          # моргание: раскрытие глаз ниже этой доли от обычного
BLINK_ABS = 0.06          # ...или ниже этого абсолютного значения
# Голова считается "отвёрнутой" только при почти профильном повороте (вид 3/4 это ещё не профиль:
# отношение носа к щекам ~0.7-0.75). Всё остальное решает точка взгляда на экране.
HEAD_YAW_LIMITS = (0.15, 0.85)

# ---------------- отображение взгляда на экран ----------------
RIDGE_LAMBDAS = (0.1, 1.0, 10.0, 100.0)  # кандидаты регуляризации (выбираются кросс-валидацией)
POINT_MIN_CUTOFF = 1.2   # One Euro фильтр точки: меньше = плавнее в покое
POINT_BETA = 2.0         # One Euro фильтр: больше = быстрее реагирует на резкие движения
# Допуск: на сколько (в долях экрана) точка взгляда может выйти за край, не считаясь "мимо".
# Вбок и вверх широкий: смотришь в бумаги, на второй монитор или задумался. Вниз узкий: там телефон.
GAZE_TOL = {"left": 0.45, "right": 0.45, "top": 0.35, "bottom": 0.15}
TOL_CV_K = 2.0           # допуск не меньше K * ошибка калибровки (хуже калибровка = мягче допуск)
MAPPER_MAX_CV = 0.22     # если ошибка калибровки больше, точке взгляда не верим: тревога только при профиле или без лица
TOL_STEP = 0.03          # шаг изменения допуска клавишами [ и ] во время работы

# ---------------- подстройка под позу ----------------
# Главная причина ложных тревог: человек сел чуть иначе, чем при калибровке. Поэтому приложение
# медленно подстраивается под позу (yaw, pitch, раскрытие глаз) в пределах DRIFT_LIMIT.
# Большие отклонения (взгляд на телефон, в сторону) НЕ подстраиваются: иначе долгий взгляд мимо
# экрана постепенно "стал бы нормой".
DRIFT_TAU = 20.0                    # сек: за сколько подстраивается (меньше = быстрее)
DRIFT_LIMIT = (0.05, 0.08, 0.04)    # максимум подстройки для yaw, pitch, eye_open
DRIFT_CAPTURE = 1.5                 # подстраиваемся, только если отклонение не больше LIMIT * CAPTURE

# ---------------- калибровка и тест точности ----------------
# По вертикали точек больше: именно там взгляд определяется хуже всего (веки закрывают зрачок)
CALIB_COLS = (0.06, 0.5, 0.94)
CALIB_ROWS = (0.06, 0.34, 0.60, 0.80, 0.94)
CALIB_SETTLE = 0.6       # сек, пока взгляд "долетает" до точки
CALIB_COLLECT = 0.8      # сек сбора данных на точке
CALIB_MIN_POINTS = 9     # минимум удачных точек для калибровки
# Шаг 2 калибровки: глаза на точке, голова медленно ходит (влево-вправо, вверх-вниз, наклон к плечу).
# Так модель учится, как глаза компенсируют движение головы, и вид 3/4, взгляд краем глаза или наклон
# головы не считаются "мимо экрана".
CALIB_HEAD_PHASE = True
CALIB_HEAD_TARGETS = ((0.5, 0.5), (0.1, 0.5), (0.9, 0.5), (0.5, 0.1), (0.5, 0.9))
CALIB_HEAD_SECONDS = 5.0
TEST_COLS = (0.2, 0.5, 0.8)
TEST_ROWS = (0.15, 0.45, 0.70, 0.88)

# ---------------- визуализация ----------------
MAP_SIZE = (640, 360)    # размер окна "карта взгляда"
HEAT_DECAY = 0.9995      # затухание тепловой карты за кадр (ближе к 1 = помнит дольше)
HEAT_MIN_SCALE = 8.0     # нормировка тепловой карты (чтобы редкие взгляды не казались горячими)
OVERLAY_OPACITY = 0.55   # прозрачность точки-оверлея: 0.1 (почти невидимая) .. 1.0 (сплошная)
